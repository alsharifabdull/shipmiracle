def _clean(s: str) -> str:
    """Drop control and format characters (escape codes, bidi overrides) from text read from a file before it is shown."""
    return "".join(c for c in s if unicodedata.category(c) not in ("Cc", "Cf", "Zl", "Zp"))


def _section(txt: str, title: str) -> List[str]:
    out, on = [], False
    for ln in (txt or "").splitlines():
        if ln.startswith("## "):
            if on:
                break
            on = ln[3:].strip() == title
            continue
        if on:
            out.append(ln)
    return out


def parse_plugins(ws=None) -> Dict[str, str]:
    """`- plugin name@marketplace | why` lines under `## Approved plugins` in skills/APPROVED.md -> {name@marketplace: why}."""
    txt = _read(_ws(ws) / "skills" / "APPROVED.md") or ""
    out = {}
    for ln in _section(txt, "Approved plugins"):
        ln = ln.rstrip()
        m = PLUGIN_LINE_RE.match(ln) if len(ln) <= MAX_LINE else None
        if m:
            out[m.group(1)] = m.group(2)
    return out


def parse_retired(ws=None) -> set:
    """Names that start a line under `## Retired` (`name (why)` or `- name | why`); a plugin is name@marketplace."""
    txt = _read(_ws(ws) / "skills" / "APPROVED.md") or ""
    out = set()
    for ln in _section(txt, "Retired"):
        m = RETIRED_RE.match(ln.strip())
        if m:
            out.add(m.group(1))
    return out


def parse_ignored(ws=None) -> Dict[str, dict]:
    """skills/IGNORED.md `- name | reason | date` -> {name: {reason, date}}; a line with an empty reason is not an ignore."""
    txt = _read(_ws(ws) / "skills" / "IGNORED.md") or ""
    out = {}
    for ln in txt.splitlines():
        ln = ln.rstrip()
        m = IGNORED_RE.match(ln) if len(ln) <= MAX_LINE else None
        if m:
            reason = _clean(m.group(2)).strip()
            if reason:
                out[m.group(1)] = {"reason": reason, "date": m.group(3) or ""}
    return out


def plugin_state(home=None) -> Tuple[Dict[str, bool], set, Optional[str]]:
    """(enabledPlugins {name: bool}, installed names, problem) from ~/.claude/settings.json and ~/.claude/plugins/installed_plugins.json. Read only."""
    home = _home(home)
    enabled: Dict[str, bool] = {}
    installed: set = set()
    problem = None
    for rel, key in ((".claude/settings.json", "enabledPlugins"), (".claude/plugins/installed_plugins.json", "plugins")):
        txt = _read(home / rel)
        if txt is None:
            continue
        try:
            d = json.loads(txt)
        except (ValueError, RecursionError):
            problem = "%s is not valid JSON" % rel
            continue
        v = d.get(key) if isinstance(d, dict) else None
        if isinstance(v, dict):
            if key == "enabledPlugins":
                enabled = {str(k): val is True for k, val in v.items()}
            else:
                installed = set(str(k) for k in v)
        elif v is not None:
            problem = "%s: %s has an unexpected shape" % (rel, key)
    return enabled, installed, problem


def claude_dir_skills(home=None) -> Tuple[List[str], bool]:
    """(names in ~/.claude/skills the skills tool does not manage, synced folder present). A symlink into ~/.agents/skills is the managed
    layout and counts once (under ~/.agents); a real folder or any other symlink is a finding; `synced` is not a skill."""
    home = _home(home)
    base = home / ".claude" / "skills"
    agents_real = os.path.realpath(str(home / ".agents" / "skills"))
    names, synced = [], False
    try:
        entries = sorted(os.listdir(str(base)))
    except OSError:
        return [], False
    for n in entries:
        if n == "synced":
            synced = True
            continue
        full = base / n
        if os.path.islink(str(full)):
            if os.path.realpath(str(full)).startswith(agents_real + os.sep):
                continue
            names.append(n)
        elif full.is_dir():
            names.append(n)
    return names, synced


def _shown(name) -> str:
    """A name that matches the strict skill/plugin patterns is shown as is; anything else (odd characters, control codes, look-alikes) as a repr() cut to 60 chars."""
    s = str(name)
    return s if (SKILL_RE.fullmatch(s) or PLUGIN_RE.fullmatch(s)) else "%s(len %d)" % (ascii(s[:60]), len(s))


def _finding(kind, name, scope, cls, level, hint="") -> dict:
    return {"kind": kind, "name": name, "scope": scope, "cls": cls, "level": level, "hint": hint}


def found_scan(ws=None, home=None, project_list=None) -> List[dict]:
    """Every skill and plugin the machine has, classed against skills/APPROVED.md, its `## Retired` list and skills/IGNORED.md. Offline, folder listings only.
    cls: approved | unlisted | retired | ignored | unmanaged | skipped | unreadable. scope: global | claude | plugin | project:NAME. Nothing is changed."""
    ws, home = _ws(ws), _home(home)
    approved = {a["skill"] for a in parse_approved(ws)}
    plug_ok = parse_plugins(ws)
    retired, ignored = parse_retired(ws), parse_ignored(ws)
    out: List[dict] = []

    def classify(kind, name, scope, bad_level, is_ok, hint_unlisted):
        if name in retired:
            out.append(_finding(kind, name, scope, "retired", "FAIL", "shipm skills remove %s" % _shown(name)))
        elif is_ok:
            out.append(_finding(kind, name, scope, "approved", "ok"))
        elif name in ignored:
            out.append(_finding(kind, name, scope, "ignored", "info", ignored[name]["reason"]))
        else:
            out.append(_finding(kind, name, scope, "unlisted", bad_level, hint_unlisted))

    def three(n, scope="global"):
        if _shown(n) != str(n):       # not a strict name: no command takes it; the owner removes it by hand
            where = {"global": "~/.agents/skills/", "claude": "~/.claude/skills/"}.get(scope)
            return "not a valid skill/plugin name; remove it by hand: %s%s" % (where or "the entry in ~/.claude/settings.json: ", _shown(n))
        n = _shown(n)
        return "shipm skills approve %s --why \"...\" | shipm skills ignore %s --reason \"...\" | shipm skills remove %s" % (n, n, n)

    for n in installed_global(home):
        classify("skill", n, "global", "FAIL", n in approved, three(n))
    cl, synced = claude_dir_skills(home)
    for n in cl:
        if n in approved and n not in retired:
            out.append(_finding("skill", n, "claude", "unmanaged", "warn", "approved name, but a real folder or foreign link in ~/.claude/skills; remove it, then bin/skills-sync"))
        else:
            classify("skill", n, "claude", "FAIL", False, three(n, "claude"))
    if synced:
        out.append(_finding("skill", "synced", "claude", "skipped", "info", "not a skill folder"))
    enabled, installed, problem = plugin_state(home)
    if problem:
        out.append(_finding("plugin", "settings", "plugin", "unreadable", "warn", problem))
    for n in sorted(set(enabled) | installed):
        if n in retired and n not in installed:
            continue        # a leftover settings entry with nothing installed: nothing to remove
        classify("plugin", n, "plugin", "FAIL" if enabled.get(n) else "info", n in plug_ok, three(n, "plugin"))
    plist = project_list
    if plist is None:
        try:
            plist = [(p.name, p.path) for p in projects.list_projects()]
        except Exception:
            plist = []
    for pname, pdir in plist:
        sk = _read(Path(pdir) / "docs" / "SKILLS.md") or ""
        for n in project_skills(pdir):
            listed = n in approved or re.search(r"(?<![\w.-])%s(?![\w.-])" % re.escape(n), sk) is not None
            classify("skill", n, "project:" + pname, "warn", listed,
                     "list it in docs/SKILLS.md (shipm skills view %s --write) | shipm skills ignore %s --reason \"...\"" % (pname, n))
    return out


def found_rows(findings: List[dict], n_global: int) -> List[Tuple[str, str]]:
    """Doctor rows from found_scan: one row per (scope, class, level) group, names joined."""
    rows: List[Tuple[str, str]] = []
    grp: Dict[tuple, List[dict]] = {}
    for f in findings:
        if f["cls"] != "approved":
            grp.setdefault((f["scope"], f["cls"], f["level"]), []).append(f)
    order = {"FAIL": 0, "warn": 1, "info": 2}
    for (scope, cls, level), fs in sorted(grp.items(), key=lambda kv: (order.get(kv[0][2], 3), kv[0][0], kv[0][1])):
        names = ", ".join(_shown(f["name"]) for f in fs)
        where = {"global": "global skills", "claude": "skills in ~/.claude/skills (a real folder or foreign link)", "plugin": "plugins"}.get(scope)
        if scope.startswith("project:"):
            where = "%s: project skills" % scope[8:]
        if cls == "unlisted":
            if scope == "plugin":
                row = "%s plugins not in skills/APPROVED.md (## Approved plugins): %s → shipm skills found" % ("enabled" if level == "FAIL" else "installed but disabled", names)
            elif scope.startswith("project:"):
                row = "%s not in skills/APPROVED.md or the project's docs/SKILLS.md: %s → shipm skills found" % (where, names)
            else:
                row = "%s not in skills/APPROVED.md: %s → shipm skills found (approve, ignore or remove)" % (where, names)
        elif cls == "retired":
            row = "retired %s still installed: %s → %s" % (where, names, "; ".join(f["hint"] for f in fs))
        elif cls == "ignored":
            row = "%s ignored on purpose (skills/IGNORED.md): %s" % (where, names)
        elif cls == "unmanaged":
            row = "%s with an approved name but not managed: %s → shipm skills found" % (where, names)
        elif cls == "skipped":
            row = "~/.claude/skills/synced skipped (not a skill folder)"
        else:
            row = "%s: %s" % (names, "; ".join(f["hint"] for f in fs))
        rows.append((level, row))
    if not any(f["scope"] == "global" and f["cls"] != "approved" for f in findings):
        rows.insert(0, ("ok", "every global skill is in skills/APPROVED.md (%d installed)" % n_global))
    plug = [f for f in findings if f["scope"] == "plugin" and f["cls"] != "unreadable"]
    if plug and all(f["cls"] == "approved" for f in plug):
        rows.append(("ok", "every installed plugin is in skills/APPROVED.md (%d)" % len(plug)))
    return rows


