def _line_text(label: str, text: Optional[str]) -> str:
    t = (text or "").strip()
    if not t:
        raise UsageError("%s is required (a short sentence)" % label)
    if "|" in t or len(t.splitlines()) != 1 or any(unicodedata.category(c) in ("Cc", "Cf", "Zl", "Zp") for c in t):
        raise UsageError("%s may not contain '|', a line break or a control character" % label)
    return t


def _insert_before(path: Path, line: str, headings: List[str]) -> None:
    """Add `line` after the last non-blank line that precedes the first heading in `headings` (else at the end of the file)."""
    lines = (_read(path) or "").split("\n")
    idx = next((i for i, l in enumerate(lines) if l.strip() in headings), None)
    if idx is None:
        while lines and lines[-1] == "":
            lines.pop()
        lines += [line, ""]
    else:
        j = idx
        while j > 0 and lines[j - 1].strip() == "":
            j -= 1
        lines[j:j] = [line]
    _atomic(path, "\n".join(lines))


def approve(name: str, why: str, packs: Optional[str] = None, ws=None, home=None) -> str:
    """Add one approved line (a skill also gets one lock entry). Returns a one-line result. Idempotent. Nothing is installed or removed."""
    paths.require_owner("shipm skills approve")
    ws, home = _ws(ws), _home(home)
    why = _line_text("--why", why)
    af = ws / "skills" / "APPROVED.md"
    if _read(af) is None:
        raise NotFound("skills/APPROVED.md not found")
    is_plugin = "@" in name
    if is_plugin and not PLUGIN_RE.fullmatch(name):
        raise UsageError("a plugin is NAME@MARKETPLACE (letters, digits, . _ -)")
    if not is_plugin and not SKILL_RE.fullmatch(name):
        raise UsageError("not a skill name: %r" % name[:64])
    if name in parse_retired(ws):
        raise SafetyError("%s is under ## Retired in skills/APPROVED.md; move it out by hand first" % name)
    if is_plugin:
        if name in parse_plugins(ws):
            return "already approved: plugin %s (nothing changed)" % name
        lines = (_read(af) or "").split("\n")
        start = next((i for i, l in enumerate(lines) if l.startswith("## ") and l[3:].strip() == "Approved plugins"), None)
        if start is not None:
            end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
            j = end
            while j > start + 1 and lines[j - 1].strip() == "":
                j -= 1
            lines[j:j] = ["- plugin %s | %s" % (name, why)]
            _atomic(af, "\n".join(lines))
        else:
            _insert_before(af, "## Approved plugins\n- plugin %s | %s\n" % (name, why), SECTION_AFTER_SKILLS[1:])
        return "approved plugin %s (one line added to skills/APPROVED.md)" % name
    if any(a["skill"] == name for a in parse_approved(ws)):
        return "already approved: skill %s (nothing changed)" % name
    ent = global_lock(home).get(name)
    src = str(ent.get("source", "")) if isinstance(ent, dict) else ""
    if not PKG_RE.fullmatch(src):
        raise SafetyError("no known source for %s (not in ~/.agents/.skill-lock.json): a skill without a source cannot be pinned. "
                          "Use `shipm skills ignore %s --reason ...`, `shipm skills remove %s`, or keep it as a project-only skill (docs/SKILLS.md)" % (name, name, name))
    th = tree_sha256(skill_dir(name, home))
    if th is None:
        raise SafetyError("%s is not installed under ~/.agents/skills, so there is nothing to record a hash of" % name)
    pk = ",".join(p.strip() for p in (packs or "global").split(",") if p.strip())
    if not pk or not re.fullmatch(r"[\w, -]+", pk):
        raise UsageError("--pack is a comma list of pack words")
    lock = load_lock(ws)
    e = {"pkg": src, "commit": UNPINNED, "tree_sha256": th,
         "path": str(ent.get("skillPath", "")).rsplit("/", 1)[0] or None, "upstream_folder_hash": ent.get("skillFolderHash")}
    lock[name] = {k: v for k, v in e.items() if v}
    write_lock(lock, ws)
    _insert_before(af, "- %s@%s | %s | %s | %s" % (src, UNPINNED, name, why, pk), SECTION_AFTER_SKILLS)
    return "approved skill %s from %s (unpinned; one line + one lock entry; bin/skills-sync --pin --online pins it)" % (name, src)


def ignore(name: str, reason: str, ws=None, today: Optional[str] = None) -> str:
    paths.require_owner("shipm skills ignore")
    ws = _ws(ws)
    reason = _line_text("--reason", reason)
    if not (SKILL_RE.fullmatch(name) or PLUGIN_RE.fullmatch(name)):
        raise UsageError("not a skill or plugin name: %r" % name[:64])
    if name in parse_ignored(ws):
        return "already ignored: %s (nothing changed)" % name
    path = ws / "skills" / "IGNORED.md"
    base = _read(path)
    base = IGNORED_HEADER if base is None else base
    if base and not base.endswith("\n"):
        base += "\n"
    _atomic(path, base + "- %s | %s | %s\n" % (name, reason, today or time.strftime("%Y-%m-%d")))
    return "ignored %s (one line added to skills/IGNORED.md)" % name


def removal_command(name: str, home=None) -> Tuple[str, List[str]]:
    """(kind, argv) for removing a found skill or plugin; refuses a name that is not installed. Nothing is run here.
    The skill verb is the one docs/owner-steps/p3-skills.sh uses; the plugin verb was not checked against --help."""
    home = _home(home)
    if "@" in name:
        if not PLUGIN_RE.fullmatch(name):
            raise UsageError("a plugin is NAME@MARKETPLACE")
        enabled, installed, _p = plugin_state(home)
        if name not in installed and name not in enabled:
            raise NotFound("plugin %s is not installed" % name)
        return "plugin", ["claude", "plugin", "uninstall", name]
    if not SKILL_RE.fullmatch(name):
        raise UsageError("not a skill name: %r" % name[:64])
    if name not in installed_global(home) and name not in claude_dir_skills(home)[0]:
        raise NotFound("skill %s is not installed globally (a project-only skill is removed by deleting that project's folder by hand)" % name)
    if name in claude_dir_skills(home)[0]:
        # a real folder or foreign link in ~/.claude/skills: the skills tool does not manage it, so its remove would do nothing (checked first;
        # remove() also prints the global command when the same name is installed globally)
        return "manual", [str(_home(home) / ".claude" / "skills" / name)]
    return "skill", ["npx", "--yes", "skills@%s" % SKILLS_NPM_VERSION, "remove", name, "-g", "-y"]


def remove(name: str, home=None, is_tty: Optional[bool] = None, ask=None, run=None, out=print) -> int:
    """Print the exact command, ask y/N, and only then run it. Refuses without a terminal. Tests pass is_tty, ask and run."""
    paths.require_owner("shipm skills remove")
    tty = sys.stdin.isatty() if is_tty is None else is_tty
    if not tty:
        raise SafetyError("shipm skills remove needs a terminal to ask y/N; run it yourself in a terminal")
    kind, argv = removal_command(name, home)
    if kind == "manual":
        out("%s is a real folder or foreign link in ~/.claude/skills, not managed by the skills tool; nothing was run." % name)
        out("Look at it, then remove it yourself: rm -r %s    (if it is a symlink: rm %s)" % (shlex.quote(argv[0]), shlex.quote(argv[0])))
        if name in installed_global(home):
            out("The same name is also installed globally; that copy is removed with: npx --yes skills@%s remove %s -g -y" % (SKILLS_NPM_VERSION, name))
        return 1
    out("would run: %s" % " ".join(argv))
    ans = (ask or input)("Remove %s %s? [y/N] " % (kind, name)).strip().lower()
    if ans not in ("y", "yes"):
        out("nothing changed")
        return 1
    rc = (run or (lambda a: subprocess.run(a, timeout=300).returncode))(argv)
    out("done" if rc == 0 else "the command exited with %s" % rc)
    return 0 if rc == 0 else 1


def found_lines(findings: List[dict], short=False) -> List[str]:
    n = {"FAIL": 0, "warn": 0, "info": 0, "ok": 0}
    for f in findings:
        n[f["level"]] = n.get(f["level"], 0) + 1
    summary = "found, not approved: %d FAIL, %d warn, %d info, %d ok" % (n["FAIL"], n["warn"], n["info"], n["ok"])
    if short:
        return [summary]
    out = ["%-4s %-6s %-40s %-18s %s" % (f["level"], f["kind"], _shown(f["name"]), f["scope"] + "/" + f["cls"], f["hint"]) for f in findings if f["level"] != "ok"]
    return out + [summary]


