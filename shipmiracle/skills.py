# ------------------------------------------------------------------ stack
def stack_of(project_dir) -> str:
    """ios | web | api | python | home | notes | other | unknown, from the project's own words (CLAUDE.md, then AGENTS.md)."""
    for f in ("CLAUDE.md", "AGENTS.md"):
        txt = _read(Path(project_dir) / f) or ""
        m = re.search(r"^- Stack:[ \t]*(.+)$", txt, re.M) or re.search(r"Stack rules — ([^\n(]+)", txt)
        if not m:
            continue
        s = m.group(1).lower()
        for key, words in (("ios", ("ios", "swift")), ("home", ("home automation", "home-assistant")), ("web", ("web", "react", "next", "vite", "frontend", "front-end")),
                           ("api", ("api", "backend", "node", "express")), ("python", ("python",)), ("notes", ("notes", "ideas", "docs only"))):
            if any(w in s for w in words):
                return key
        if "{{" in s or "decide" in s or "other" in s:
            return "other"
    return "unknown"


