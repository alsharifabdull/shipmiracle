def _find_folder(repo: Path, skill: str, hint: Optional[str]) -> Optional[Path]:
    if hint:
        real_repo = os.path.realpath(str(repo))
        cand = os.path.realpath(str(repo / hint))
        if cand != real_repo and cand.startswith(real_repo + os.sep) and os.path.isfile(os.path.join(cand, "SKILL.md")):
            return Path(cand)
    hits = _folder_hits(repo, skill)
    hits.sort(key=lambda x: (0 if "skills" in x.relative_to(repo).parts else 1, len(x.parts)))
    return hits[0] if hits else None


def _folder_hits(repo: Path, skill: str) -> List[Path]:
    """Every folder in `repo` (not .git) named `skill` that holds a SKILL.md."""
    hits = []
    for dp, dns, fns in os.walk(str(repo)):
        dns[:] = [d for d in dns if d != ".git"]
        if os.path.basename(dp) == skill and "SKILL.md" in fns:
            hits.append(Path(dp))
    return hits


GIT_PLAIN = ["-c", "filter.lfs.smudge=", "-c", "filter.lfs.process=", "-c", "filter.lfs.required=false", "-c", "core.autocrlf=false"]   # no LFS filters, no line-ending rewrite: the files are the commit's bytes


def checkout(pkg: str, commit: str, dest: Path) -> Path:
    """Clone `pkg` into dest and check out exactly `commit` (git clone + checkout: the pinned path; P3-8). Raises ShipmiracleError on failure."""
    if not re.fullmatch(r"[0-9a-f]{7,64}", commit or ""):
        raise ShipmiracleError("%s is not pinned to a commit" % pkg)
    p = _git(GIT_PLAIN + ["clone", "--quiet", "--no-checkout", repo_url(pkg), str(dest)])
    if p.returncode != 0:
        raise ShipmiracleError("clone of %s failed: %s" % (pkg, (p.stderr or "").strip()[:160]))
    p = _git(GIT_PLAIN + ["-c", "advice.detachedHead=false", "checkout", "--quiet", commit], cwd=str(dest))
    if p.returncode != 0:
        raise ShipmiracleError("commit %s not found in %s" % (commit[:12], pkg))
    return dest


def escaping_links(folder: Path) -> List[str]:
    """Symlinks inside `folder` whose target resolves outside it (a skill must not reach into the rest of the disk)."""
    real = os.path.realpath(str(folder))
    bad = []
    for dp, dns, fns in os.walk(str(folder)):
        for n in dns + fns:
            full = os.path.join(dp, n)
            if os.path.islink(full):
                t = os.path.realpath(full)
                if t != real and not t.startswith(real + os.sep):
                    bad.append(os.path.relpath(full, str(folder)))
    return bad


def install_skill(skill: str, entry: dict, target_root: Path, link_root: Optional[Path], dry=False, online=False) -> Tuple[str, str]:
    """Install one skill at its pinned commit into target_root/<skill> (and a relative symlink in link_root/<skill>).
    -> (status, detail): ok | exists | unpinned | dry | FAIL. An existing folder is never overwritten."""
    if not SKILL_RE.fullmatch(skill):
        return "FAIL", "bad skill name"
    commit = entry.get("commit")
    dest = target_root / skill
    if dest.exists():
        have = tree_sha256(dest)
        want = entry.get("tree_sha256")
        return "exists", ("same files as the lock" if (want and have == want) else "different from the lock: kept, not overwritten") + " (%s)" % dest
    if commit == UNPINNED or not commit:
        return "unpinned", "no commit recorded: run bin/skills-sync --pin --online first (nothing is installed unpinned)"
    if not re.fullmatch(r"[0-9a-f]{64}", str(entry.get("tree_sha256") or "")):
        return "FAIL", "skills.lock.json has no tree_sha256 for %s: refusing to install without a hash to verify" % skill
    if dry:
        return "dry", "would clone %s at %s and copy %s to %s" % (entry["pkg"], commit[:12], skill, dest)
    if not online:
        return "offline", "installing %s needs a git clone of %s: add --online" % (skill, entry["pkg"])
    tmp = Path(tempfile.mkdtemp(prefix="shipmiracle-skill-"))
    try:
        repo = checkout(entry["pkg"], commit, tmp / "repo")
        src = _find_folder(repo, skill, entry.get("path"))
        if src is None:
            return "FAIL", "skill folder %s not found in %s@%s" % (skill, entry["pkg"], commit[:12])
        esc = escaping_links(src)
        if esc:
            return "FAIL", "%s has symlinks that point outside the skill folder (%s): nothing installed" % (skill, ", ".join(esc[:3]))
        target_root.mkdir(parents=True, exist_ok=True)
        staging = target_root / (".%s.tmp-%d" % (skill, os.getpid()))
        shutil.copytree(str(src), str(staging), symlinks=True, ignore=shutil.ignore_patterns(".git"))
        want = entry.get("tree_sha256")
        if tree_sha256(staging) != want:
            shutil.rmtree(str(staging), ignore_errors=True)
            return "FAIL", "files of %s at %s differ from skills.lock.json (tree_sha256): nothing installed" % (skill, commit[:12])
        os.replace(str(staging), str(dest))
        if link_root is not None and not link_root.is_symlink():
            link_root.mkdir(parents=True, exist_ok=True)
            ln = link_root / skill
            if not os.path.lexists(str(ln)):
                os.symlink(os.path.relpath(str(dest), str(link_root)), str(ln))
        return "ok", "installed %s at %s" % (skill, commit[:12])
    except (ShipmiracleError, OSError, subprocess.SubprocessError) as e:
        return "FAIL", str(e)[:200]
    finally:
        shutil.rmtree(str(tmp), ignore_errors=True)


def sync_global(ws=None, home=None, dry=False, online=False) -> List[Tuple[str, str, str]]:
    ws, home = _ws(ws), _home(home)
    lock = load_lock(ws)
    out = []
    for a in parse_approved(ws):
        if "global" not in a["packs"]:
            continue
        s = a["skill"]
        entry = dict(lock.get(s) or {"pkg": a["pkg"], "commit": a["commit"]})
        st, why = install_skill(s, entry, home / ".agents" / "skills", home / ".claude" / "skills", dry, online)
        out.append((s, st, why))
    return out


def sync_project(project, pack, ws=None, home=None, dry=False, online=False) -> List[Tuple[str, str, str]]:
    ws, home = _ws(ws), _home(home)
    p = projects.get(project) if not os.path.isdir(str(project)) else None
    pdir = Path(p.path) if p else Path(project)
    if not pdir.is_dir():
        raise NotFound("no such project: %s" % project)
    lock = load_lock(ws)
    members = [a for a in parse_approved(ws) if pack in a["packs"]]
    if not members:
        raise UsageError("no skills in pack %r (packs: %s)" % (pack, ", ".join(sorted({x for a in parse_approved(ws) for x in a["packs"]}))))
    out, pins = [], project_pins(pdir)
    for a in members:
        entry = dict(lock.get(a["skill"]) or {"pkg": a["pkg"], "commit": a["commit"]})
        st, why = install_skill(a["skill"], entry, pdir / ".agents" / "skills", pdir / ".claude" / "skills", dry, online)
        out.append((a["skill"], st, why))
        if st == "ok":
            pins[a["skill"]] = {"pkg": entry["pkg"], "commit": entry["commit"], "tree_sha256": tree_sha256(pdir / ".agents" / "skills" / a["skill"])}
    if not dry and any(s == "ok" for _n, s, _w in out):
        _atomic(pdir / ".agents" / "skills.pins.json", json.dumps(pins, indent=1, sort_keys=True) + "\n")
    return out


def _files_of(folder: Path) -> set:
    out = set()
    for dp, dns, fns in os.walk(str(folder)):
        dns[:] = [d for d in dns if d != ".git"]
        for n in fns + [d for d in dns if os.path.islink(os.path.join(dp, d))]:
            if n != ".DS_Store":
                out.add(os.path.relpath(os.path.join(dp, n), str(folder)))
    return out


def _flist(files) -> str:
    """Up to 20 relative file names, sorted; upstream names that are not plain printable ASCII are shown escaped; '(N total)' always."""
    names = sorted(files)
    shown = [x if (x.isascii() and x.isprintable()) else ascii(x[:80]) for x in names[:20]]
    return "%s (%d total)" % (", ".join(shown) or "none", len(names))


def _checkout_hash(clone: Path, commit: str, skill: str, folder: Optional[str], tmp: Path) -> Tuple[Optional[str], set]:
    """(tree_sha256, set of relative files) of the skill folder exactly as install_skill would produce it from `commit` (same checkout, same folder
    search, .git ignored). `clone` is the --no-checkout clone pin() already made; a cheap local clone is checked out at `commit` in a fresh
    private folder under `tmp` (never a path built from the skill name), removed on every exit."""
    dest = Path(tempfile.mkdtemp(dir=str(tmp), prefix="co-"))
    try:
        p = _git(GIT_PLAIN + ["clone", "--quiet", "--no-checkout", str(clone), str(dest)])
        if p.returncode != 0:
            raise ShipmiracleError("local checkout failed: %s" % (p.stderr or "").strip()[:120])
        p = _git(GIT_PLAIN + ["-c", "advice.detachedHead=false", "checkout", "--quiet", commit], cwd=str(dest))
        if p.returncode != 0:
            raise ShipmiracleError("commit %s not found in the clone" % commit[:12])
        src = _find_folder(dest, skill, folder)
        if src is None:
            raise ShipmiracleError("skill folder %s not found at %s" % (skill, commit[:12]))
        if folder and os.path.relpath(str(src), os.path.realpath(str(dest))) != os.path.normpath(folder):
            raise ShipmiracleError("the folder install would copy (%s) is not the folder whose git hash matched (%s)" % (os.path.relpath(str(src), os.path.realpath(str(dest))), folder))
        if escaping_links(src):
            raise ShipmiracleError("%s has symlinks that point outside the skill folder at %s" % (skill, commit[:12]))
        return tree_sha256(src), _files_of(src)
    finally:
        shutil.rmtree(str(dest), ignore_errors=True)


def pin(ws=None, home=None, only: Optional[List[str]] = None, repin: bool = False, out=print, is_tty: Optional[bool] = None, ask=None) -> List[Tuple[str, str, str]]:
    """Resolve `unpinned` entries (NETWORK: git clone). A commit is recorded only when its folder has exactly the git tree hash the skills CLI
    recorded at install time (skillFolderHash in ~/.agents/.skill-lock.json); otherwise the entry stays unpinned. The lock's tree_sha256 is then
    taken from the PINNED CHECKOUT (what install_skill will produce), not from the CLI's installed copy. Rewrites the lock and APPROVED.md.
    repin=True (owner only, needs a terminal; `only` must name existing skills, never 'all'): redo the tree_sha256 of an entry that is ALREADY pinned.
    It never moves the commit (if the pinned commit no longer has the CLI's folder hash that is an update: FAIL, use a normal pin after review).
    Before writing it prints commit and tree_sha256 before -> after plus the files added/removed against the installed copy, and asks y/N."""
    ws, home = _ws(ws), _home(home)
    lock = load_lock(ws)
    tty = False
    if repin:
        paths.require_owner("bin/skills-sync --repin")
        names = list(only or [])
        if not names or any(n in ("all", "*") for n in names):
            raise UsageError("--repin needs explicit skill names (never 'all')")
        missing = [n for n in names if n not in lock]
        if missing:
            raise UsageError("--repin: not in skills.lock.json: %s" % ", ".join(_shown(n) for n in missing))
        tty = sys.stdin.isatty() if is_tty is None else is_tty
        if not tty:
            raise SafetyError("--repin shows what changes and asks y/N: run it yourself in a terminal")
    glock = global_lock(home)
    res, changed = [], False
    clones: Dict[str, Path] = {}
    tmp = Path(tempfile.mkdtemp(prefix="shipmiracle-pin-"))
    try:
        for s in sorted(lock):
            e = lock[s]
            if (only and s not in only) or (repin and s not in (only or [])):
                continue
            if not isinstance(e, dict):
                res.append((_shown(s), "FAIL", "lock entry is not an object"))
                continue
            if not repin and e.get("commit") != UNPINNED:
                continue
            if not SKILL_RE.fullmatch(s) or not isinstance(e, dict) or not PKG_RE.fullmatch(str(e.get("pkg", ""))):
                res.append((_shown(s), "FAIL", "bad skill name or package in skills.lock.json"))
                continue
            bad = "FAIL" if repin else "unpinned"
            g = glock.get(s) or {}
            folder = str(g.get("skillPath", "")).rsplit("/", 1)[0] if g.get("skillPath") else e.get("path")
            want = g.get("skillFolderHash") or e.get("upstream_folder_hash")
            if not folder or not want:
                res.append((s, bad, "no recorded upstream folder hash"))
                continue
            prev = e.get("commit")
            try:
                if e["pkg"] not in clones:
                    c = tmp / e["pkg"].replace("/", "_")
                    p = _git(GIT_PLAIN + ["clone", "--quiet", "--no-checkout", repo_url(e["pkg"]), str(c)])
                    if p.returncode != 0:
                        raise ShipmiracleError("clone failed: %s" % (p.stderr or "").strip()[:120])
                    clones[e["pkg"]] = c
                c = clones[e["pkg"]]
                found = None
                if repin:
                    cand = [prev] if isinstance(prev, str) and re.fullmatch(r"[0-9a-f]{7,64}", prev) else []
                else:
                    cand = _git(["log", "--format=%H", "--", folder], cwd=str(c)).stdout.split()[:200]
                for h in cand:
                    r = _git(["rev-parse", "%s:%s" % (h, folder)], cwd=str(c))
                    if r.returncode == 0 and r.stdout.strip() == want:
                        found = h
                        break
            except (ShipmiracleError, OSError, subprocess.SubprocessError) as ex:
                res.append((s, "FAIL", str(ex)[:160]))
                continue
            if not found:
                res.append((s, bad, ("pinned commit %s is unreachable or no longer has the CLI's folder hash: re-pinning would change the commit; that is an update, "
                                     "use a normal pin after review" % str(prev)[:12]) if repin else "no commit has the folder hash the CLI installed"))
                continue
            try:
                co_hash, co_files = _checkout_hash(c, found, s, folder, tmp)
            except (ShipmiracleError, OSError, subprocess.SubprocessError) as ex:
                res.append((s, "FAIL", "pinned checkout not usable: %s" % str(ex)[:140]))
                continue
            old_tree = str(e.get("tree_sha256"))
            if repin:
                line = "commit %s -> %s, tree_sha256 %s -> %s" % (str(prev)[:12], found[:12], old_tree[:12], str(co_hash)[:12])
                out("%s: %s" % (s, line))
                if old_tree == co_hash:
                    res.append((s, "kept", "the lock already equals the pinned checkout; nothing written. If the installed copy differs, reinstall from the pin: %s, then bin/skills-sync --online" % _removal_text(s, home)))
                    continue
                have = skill_dir(s, home)
                if have.is_dir():
                    inst_files = _files_of(have)
                    out("  files only in the pinned checkout (added vs installed): %s" % _flist(co_files - inst_files))
                    out("  files only in the installed copy (removed vs checkout): %s" % _flist(inst_files - co_files))
                else:
                    out("  (not installed globally: nothing to compare)")
                try:
                    ans = (ask or input)("Write the new tree_sha256 for %s to skills.lock.json? [y/N] " % s).strip().lower()
                except EOFError:
                    out("  no answer (end of input): treated as n")
                    ans = "n"
                if ans not in ("y", "yes"):
                    res.append((s, "kept", "declined: lock unchanged"))
                    continue
            e["commit"] = found if not repin else prev
            e["path"] = folder
            e["tree_sha256"] = co_hash
            if "upstream_folder_hash" in e:
                e["upstream_folder_hash"] = want
            lock[s] = e
            changed = True
            if repin:
                res.append((s, "repinned", "%s. Next: remove the installed copy (%s), then bin/skills-sync --online (install keeps an existing folder)" % (line, _removal_text(s, home))))
            else:
                res.append((s, "pinned", "%s (tree_sha256 %s)" % (found[:12], str(co_hash)[:12])))
        if changed:
            write_lock(lock, ws)
            txt = _read(_ws(ws) / "skills" / "APPROVED.md") or ""
            new = []
            for ln in txt.splitlines():
                m = LINE_RE.match(ln)
                if m and m.group(3) in lock and lock[m.group(3)]["commit"] != m.group(2):
                    ln = ln.replace("%s@%s" % (m.group(1), m.group(2)), "%s@%s" % (m.group(1), lock[m.group(3)]["commit"]), 1)
                new.append(ln)
            _atomic(_ws(ws) / "skills" / "APPROVED.md", "\n".join(new) + "\n")
    finally:
        shutil.rmtree(str(tmp), ignore_errors=True)
    return res


def pin_from_commit(names, ws=None, home=None, out=print, is_tty: Optional[bool] = None, ask=None) -> List[Tuple[str, str, str]]:
    """Owner only, needs a terminal, explicit names (never 'all'). For an APPROVED skill whose lock entry has a pinned commit but NO tree_sha256
    (never installed, so there is no skills CLI copy for pin/--repin to read): clone the package at the pinned commit (same checkout code as the
    installer), find the skill folder (it must be the ONLY folder of that name with a SKILL.md in the repo), set `path` and `tree_sha256` from that
    checkout, print path/hash before -> after and the file list, ask y/N on the terminal, and write only skills/skills.lock.json (atomically).
    The commit is never changed, APPROVED.md is never touched, an entry that already has a tree_sha256 is refused (that is --repin).
    -> rows (name, pinned | kept | FAIL, detail). NETWORK: git clone."""
    ws, home = _ws(ws), _home(home)
    paths.require_owner("bin/skills-sync --from-commit")
    names = list(names or [])
    if not names or any(n in ("", "all", "*") for n in names):
        raise UsageError("--from-commit needs explicit skill names (never 'all')")
    names = list(dict.fromkeys(names))
    tty = terminal.can_open() if is_tty is None else is_tty
    if not tty:
        raise SafetyError("--from-commit shows what changes and asks y/N: run it yourself in a terminal")
    lock = load_lock(ws)
    approved = {a["skill"]: a for a in parse_approved(ws)}
    for n in names:
        e = lock.get(n)
        if not SKILL_RE.fullmatch(n):
            raise UsageError("--from-commit: bad skill name %s" % _shown(n))
        if n not in approved:
            raise UsageError("--from-commit: %s is not in skills/APPROVED.md (approve it first)" % n)
        if not isinstance(e, dict):
            raise UsageError("--from-commit: %s has no entry in skills.lock.json" % n)
        if not re.fullmatch(r"[0-9a-f]{7,64}", str(e.get("commit") or "")):
            raise UsageError("--from-commit: %s is not pinned to a commit in skills.lock.json (this command never picks a commit)" % n)
        if e.get("pkg") != approved[n]["pkg"] or e["commit"] != approved[n]["commit"]:
            raise UsageError("--from-commit: skills/APPROVED.md and skills.lock.json name a different package or commit for %s" % n)
        if not PKG_RE.fullmatch(str(e["pkg"])):
            raise UsageError("--from-commit: bad package name for %s" % n)
        if e.get("tree_sha256"):
            raise UsageError("--from-commit: %s already has a tree_sha256; to refresh it use --pin --online --repin %s" % (n, n))
    res, changed = [], False
    clones: Dict[Tuple[str, str], Path] = {}
    tmp = Path(tempfile.mkdtemp(prefix="shipmiracle-skill-"))
    try:
        for n in names:
            e = lock[n]
            try:
                key = (e["pkg"], e["commit"])
                if key not in clones:
                    clones[key] = checkout(e["pkg"], e["commit"], tmp / ("repo%d" % len(clones)))
                repo = clones[key]
                hits = _folder_hits(repo, n)
                if not hits:
                    res.append((n, "FAIL", "no folder %s with a SKILL.md in %s@%s" % (n, e["pkg"], e["commit"][:12])))
                    continue
                if len(hits) > 1:
                    res.append((n, "FAIL", "ambiguous: %d folders named %s hold a SKILL.md (%s): nothing written" % (len(hits), n, _flist({os.path.relpath(str(h), str(repo)) for h in hits}))))
                    continue
                src = _find_folder(repo, n, None)
                rel = os.path.relpath(str(src), str(repo))
                if not (rel.isascii() and rel.isprintable()):
                    res.append((n, "FAIL", "the folder path is not plain printable ASCII (%s): nothing written" % ascii(rel[:80])))
                    continue
                back = _find_folder(repo, n, rel)
                if back is None or os.path.realpath(str(back)) != os.path.realpath(str(src)):
                    res.append((n, "FAIL", "install would copy a different folder than %s: nothing written" % rel))
                    continue
                esc = escaping_links(src)
                if esc:
                    res.append((n, "FAIL", "%s has symlinks that point outside the skill folder (%s): nothing written" % (n, ", ".join(ascii(x[:60]) for x in esc[:3]))))
                    continue
                new_hash, files = tree_sha256(src), _files_of(src)
            except (ShipmiracleError, OSError, subprocess.SubprocessError) as ex:
                res.append((n, "FAIL", str(ex)[:160]))
                continue
            out("%s (%s at %s):" % (n, e["pkg"], e["commit"][:12]))
            out("  path:        %s -> %s" % (e.get("path") or "(none)", rel))
            out("  tree_sha256: %s -> %s" % (e.get("tree_sha256") or "(none)", new_hash))
            out("  files: %s" % _flist(files))
            try:
                ans = (ask or terminal.ask_line)("Write this path and tree_sha256 for %s to skills/skills.lock.json? [y/N] " % n).strip().lower()
            except EOFError:
                out("  no answer (end of input): treated as n")
                ans = "n"
            except OSError as ex:
                res.append((n, "FAIL", "no terminal to ask on: %s" % str(ex)[:80]))
                continue
            if ans not in ("y", "yes"):
                res.append((n, "kept", "declined: lock unchanged"))
                continue
            lock[n] = dict(e, path=rel, tree_sha256=new_hash)
            changed = True
            res.append((n, "pinned", "path %s, tree_sha256 %s. Next: bin/skills-sync --online installs it and checks this hash" % (rel, new_hash[:12])))
        if changed:
            write_lock(lock, ws)
    finally:
        shutil.rmtree(str(tmp), ignore_errors=True)
    return res


def _removal_text(name: str, home=None) -> str:
    """The exact removal command `shipm skills remove` would print for an installed skill (text only, nothing is run)."""
    try:
        kind, argv = removal_command(name, home)
    except ShipmiracleError:
        return "shipm skills remove %s" % name
    return " ".join(argv) if kind == "skill" else "rm -r %s" % shlex.quote(argv[0])


def make_lock(ws=None, home=None) -> dict:
    """Build the lock from APPROVED.md and what is installed now (tree hash of the installed folder). Existing pinned commits are kept.
    Commits are never invented: an entry without a recorded commit is `unpinned`."""
    ws, home = _ws(ws), _home(home)
    old = load_lock(ws)
    g = global_lock(home)
    lock = {}
    for a in parse_approved(ws):
        s = a["skill"]
        e = {"pkg": a["pkg"], "commit": old.get(s, {}).get("commit") or a["commit"], "tree_sha256": tree_sha256(skill_dir(s, home))}
        if s in g:
            e["path"] = str(g[s].get("skillPath", "")).rsplit("/", 1)[0] or None
            e["upstream_folder_hash"] = g[s].get("skillFolderHash")
        lock[s] = {k: v for k, v in e.items() if v}
    return lock


