_ONDEMAND_RE = re.compile(r"^On demand \([^)]*\):\s*(.+?)\.?\s*$", re.M)
_TOKEN_RE = re.compile(r"^[a-z0-9][a-z0-9:*-]*$")


def on_demand_names(body: str) -> List[str]:
    m = _ONDEMAND_RE.search(body or "")
    if not m:
        return []
    out = []
    for part in re.split(r",| and ", re.sub(r"\([^)]*\)", "", m.group(1))):
        t = part.strip()
        if _TOKEN_RE.match(t) and t not in out:
            out.append(t)
    return out


def _skill_present(name, project_dir, home) -> str:
    if "*" in name:
        pat = re.compile("^" + re.escape(name).replace(r"\*", ".*") + "$")
        found = any(pat.match(n) for n in project_skills(project_dir)) or any(pat.match(n) for n in installed_global(home))
        return "yes" if found else "no"
    return "yes" if agents.skill_exists(name, project_dir, home) else "no"


def role_table(project_dir, ws=None, home=None) -> List[dict]:
    """One row per agent visible to the project: project file > user file > master file (masters stand in until the install ran)."""
    ws, home = _ws(ws), _home(home)
    names = set(agents._names_in(agents.masters_dir(ws))) | set(agents._names_in(agents.user_dir(home))) | set(agents._names_in(Path(project_dir) / ".claude" / "agents"))
    rows = []
    for n in sorted(names):
        src = None
        for layer, p in (("project", Path(project_dir) / ".claude" / "agents" / (n + ".md")), ("user", agents.user_dir(home) / (n + ".md")),
                         ("master", agents.masters_dir(ws) / (n + ".md"))):
            txt = _read(p)
            if txt is not None:
                src = (layer, txt)
                break
        if not src:
            continue
        info = agents.parse(src[1])
        rows.append({"role": n, "layer": src[0], "flow": info["role"] or "support", "preload": info["skills"], "on_demand": on_demand_names(info["body"])})
    return rows


def render_view(project_dir, ws=None, home=None, today=None) -> str:
    ws, home = _ws(ws), _home(home)
    pdir = Path(project_dir)
    name = pdir.name
    today = today or time.strftime("%Y-%m-%d")
    old, why = team.read_text(pdir / "docs" / "SKILLS.md", root=pdir)
    if old is None and why:
        raise SafetyError("docs/SKILLS.md %s: not regenerated, so the Team table cannot be lost" % why)
    old = old or ""
    tstate, toff, tdetail = team.find_block(old)
    if tstate == "damaged":
        raise SafetyError("the Team block in docs/SKILLS.md is damaged (%s): fix it by hand, nothing was regenerated" % tdetail)
    tblock = old[toff[0]:toff[3]] if tstate == "ok" else None
    if tblock is not None and len(tblock.encode("utf-8")) > team.MAX_BLOCK:
        raise SafetyError("the Team block in docs/SKILLS.md is larger than %d KB: shorten it by hand, nothing was regenerated" % (team.MAX_BLOCK // 1024))
    m = REVIEW_RE.search(old)
    review = (m.group(1) if m and m.group(1) else "not done")
    sm = STACK_LINE_RE.search(old)
    stack = stack_of(pdir)
    lines = [GEN_HEADER, "# SKILLS — %s" % name, "", "Skills review: %s" % review, "Reviewed stack: %s" % (sm.group(1) if sm and sm.group(1) else ("unknown" if review == "not done" else stack)), ""]
    lines += ["Stack now: %s. Global skills (every project) are the `global` lines of `skills/APPROVED.md` in the Shipmiracle engine folder; pack skills are installed per project, pinned by commit." % stack, ""]
    if tblock is not None:          # the Team block is written by the lead, never by this generator: copied forward exactly (a missing block is not invented)
        lines += [team.HEADING, tblock[:-1] if tblock.endswith("\n") else tblock, ""]
    lines += ["## Roles: preloaded (`skills:`) and on demand (Skill tool)", "| Role | Source | Preload | On demand | Present |", "|---|---|---|---|---|"]
    for r in role_table(pdir, ws, home):
        allsk = r["preload"] + r["on_demand"]
        missing = [s for s in allsk if _skill_present(s, pdir, home) == "no"]
        lines.append("| %s | %s | %s | %s | %s |" % (r["role"], r["layer"], ", ".join(r["preload"]) or "-", ", ".join(r["on_demand"]) or "-",
                                                    "all" if not missing else "missing: " + ", ".join(missing)))
    lines += ["", "## Project skills", "| Skill | Package | Pin | Why | Approved |", "|---|---|---|---|---|"]
    pins, clock = project_pins(pdir), project_cli_lock(pdir)
    app = {a["skill"]: a for a in parse_approved(ws)}
    ps = project_skills(pdir)
    if not ps:
        lines.append("| - | - | - | none installed | - |")
    for s in ps:
        p = pins.get(s) or {}
        c = clock.get(s) or {}
        pkg = p.get("pkg") or c.get("source") or "unknown"
        pin = p.get("commit") or ("hash " + str(c["computedHash"])[:10] if c.get("computedHash") else "unpinned")
        lines.append("| %s | %s | %s | %s | %s |" % (s, pkg, pin, app[s]["why"][:60] if s in app else "-", "yes (APPROVED)" if s in app else "project-only"))
    lines += ["", "## Stack packs"]
    packs = STACK_PACKS.get(stack, [])
    if not packs:
        lines.append("No pack is defined for stack `%s`." % stack)
    for pk in packs:
        members = [a for a in parse_approved(ws) if pk in a["packs"]]
        have = [a["skill"] for a in members if a["skill"] in ps]
        todo = [a["skill"] for a in members if a["skill"] not in ps]
        lines.append("- %s pack: installed %s; missing %s → `bin/skills-sync --project %s --pack %s`" % (pk, ", ".join(have) or "none", ", ".join(todo) or "none", name, pk))
    lines += ["", "To look for a skill on a topic the lead runs `npx skills find <topic>`; read its SKILL.md first; only the owner approves an install.", ""]
    return "\n".join(lines)


def view(project, ws=None, home=None, write=False, today=None, mark_reviewed=False) -> Tuple[str, Optional[str]]:
    """-> (text, written path or None). Default is a dry run (nothing written). --write replaces only <project>/docs/SKILLS.md, atomically,
    and only when the content changes (the session-start hook uses the file's age)."""
    p = projects.get(project) if not os.path.isdir(str(project)) else None
    pdir = Path(p.path) if p else Path(project)
    if not pdir.is_dir():
        raise NotFound("no such project: %s" % project)
    today = today or time.strftime("%Y-%m-%d")
    text = render_view(pdir, ws, home, today)
    if mark_reviewed:
        text = REVIEW_RE.sub("Skills review: %s" % today, text, count=1)
        text = STACK_LINE_RE.sub("Reviewed stack: %s" % stack_of(pdir), text, count=1)
    if not write:
        return text, None
    target = pdir / "docs" / "SKILLS.md"
    if (team.read_text(target, root=pdir)[0] or "") == text:
        return text, str(target)
    _atomic(target, text)
    return text, str(target)


