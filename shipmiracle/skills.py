def _atomic(path, text: str, mode: int = 0o644) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix="." + path.name + ".")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        os.chmod(tmp, mode)
        os.replace(tmp, str(path))
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def _read(path) -> Optional[str]:
    try:
        with open(str(path), encoding="utf-8", errors="replace") as f:
            return f.read(2 * 1024 * 1024)
    except OSError:
        return None


def parse_approved(ws=None) -> List[dict]:
    """Every `- pkg@commit | skill | why | packs` line. Other bullets (prose) are ignored on purpose."""
    txt = _read(_ws(ws) / "skills" / "APPROVED.md") or ""
    out = []
    for ln in txt.splitlines():
        m = LINE_RE.match(ln)
        if m:
            out.append({"pkg": m.group(1), "commit": m.group(2), "skill": m.group(3), "why": m.group(4),
                        "packs": [p.strip() for p in m.group(5).split(",") if p.strip()]})
    return out


def lock_path(ws=None) -> Path:
    return _ws(ws) / "skills" / "skills.lock.json"


def load_lock(ws=None) -> Dict[str, dict]:
    txt = _read(lock_path(ws))
    if not txt:
        return {}
    try:
        d = json.loads(txt)
    except (ValueError, RecursionError):
        raise ShipmiracleError("skills/skills.lock.json is not valid JSON")
    return d if isinstance(d, dict) else {}


def write_lock(lock: dict, ws=None) -> None:
    _atomic(lock_path(ws), json.dumps(lock, indent=1, sort_keys=True) + "\n")


def tree_sha256(folder) -> Optional[str]:
    """Deterministic digest of a skill folder: sorted relative paths with the sha256 of each file (symlinks: their target text).
    .git and .DS_Store are skipped. None when the folder does not exist."""
    root = Path(folder)
    if not root.is_dir():
        return None
    lines = []
    for dp, dns, fns in os.walk(str(root)):
        dns[:] = sorted(d for d in dns if d != ".git")
        for dn in list(dns):
            full = os.path.join(dp, dn)
            if os.path.islink(full):
                lines.append("L %s %s" % (os.path.relpath(full, str(root)), os.readlink(full)))
                dns.remove(dn)
        for fn in sorted(fns):
            if fn == ".DS_Store":
                continue
            full = os.path.join(dp, fn)
            rel = os.path.relpath(full, str(root))
            if os.path.islink(full):
                lines.append("L %s %s" % (rel, os.readlink(full)))
                continue
            h = hashlib.sha256()
            with open(full, "rb") as f:
                for chunk in iter(lambda: f.read(1 << 20), b""):
                    h.update(chunk)
            lines.append("F %s %s" % (rel, h.hexdigest()))
    return hashlib.sha256(("\n".join(sorted(lines)) + "\n").encode("utf-8")).hexdigest()


