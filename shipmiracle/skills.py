def description_bytes(folder) -> int:
    """Bytes of the `description:` frontmatter value of a SKILL.md (what the prefix carries for it)."""
    txt = _read(Path(folder) / "SKILL.md") or ""
    m = re.match(r"---\r?\n(.*?)\r?\n---", txt, re.S)
    if not m:
        return 0
    dm = re.search(r"^description:[ \t]*(.*(?:\n[ \t]+.*)*)", m.group(1), re.M)
    return len(dm.group(1).strip().encode("utf-8")) if dm else 0


