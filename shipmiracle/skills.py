def _days_since(date_s: str, now: float) -> Optional[int]:
    try:
        t = time.mktime(time.strptime(date_s, "%Y-%m-%d"))
    except (ValueError, OverflowError):
        return None
    return int((now - t) // 86400)


def doctor_rows(ws=None, home=None, now=None, projects_dir=None, project_list=None) -> List[Tuple[str, str]]:
    """[(level, text)] with level ok | warn | FAIL | info, in doctor's format."""
    ws, home = _ws(ws), _home(home)
    now = now if now is not None else time.time()
    rows: List[Tuple[str, str]] = []
    app = parse_approved(ws)
    by_skill = {a["skill"]: a for a in app}
    lock = load_lock(ws)
    inst = installed_global(home)
    plist = project_list
    if plist is None:
        try:
            plist = [(p.name, p.path) for p in projects.list_projects()]
        except Exception:
            plist = []
    rows.extend(found_rows(found_scan(ws, home, plist), len(inst)))
    stray = [n for n in inst if n in by_skill and "global" not in by_skill[n]["packs"]]
    if stray:
        rows.append(("warn", "global skills that belong to a project pack: %s → docs/owner-steps/p3-skills.sh" % ", ".join(stray)))
    missing = [a["skill"] for a in app if "global" in a["packs"] and a["skill"] not in inst]
    if missing:
        rows.append(("warn", "approved global skills not installed: %s → bin/skills-sync" % ", ".join(missing)))
    unp = sorted(k for k, e in lock.items() if isinstance(e, dict) and e.get("commit") == UNPINNED)
    bad_sync = [a["skill"] for a in app if lock.get(a["skill"], {}).get("commit") != a["commit"] or lock.get(a["skill"], {}).get("pkg") != a["pkg"]]
    if bad_sync or set(by_skill) != set(lock):
        rows.append(("FAIL", "skills/APPROVED.md and skills.lock.json disagree (%s) → bin/skills-sync --pin" % (", ".join(sorted(set(bad_sync) | (set(by_skill) ^ set(lock))))[:120] or "?")))
    if unp:
        rows.append(("info", "%d approved skill(s) not pinned to a commit yet (a new Mac gets none of them until pinned; not an error): %s → bin/skills-sync --pin --online" % (len(unp), ", ".join(unp))))
    drift = [k for k, e in lock.items() if isinstance(e, dict) and e.get("tree_sha256") and k in inst and tree_sha256(skill_dir(k, home)) not in (None, e["tree_sha256"])]
    if drift:
        pinned_drift = sorted(k for k in drift if lock[k].get("commit") != UNPINNED and SKILL_RE.fullmatch(k))
        txt = "installed skill files differ from skills.lock.json: %s → bin/skills-sync --diff" % ", ".join(_shown(k) for k in sorted(drift))
        if pinned_drift:
            txt += ("; pinned: if the install is refused with 'differ from skills.lock.json', run in your terminal bin/skills-sync --pin --online --repin %s"
                    " (it never moves the commit), then remove the installed copy (npx --yes skills@%s remove NAME -g -y) and run bin/skills-sync --online;"
                    " if repin says the lock already equals the pinned checkout, only reinstall from the pin (remove, then bin/skills-sync --online)"
                    % (",".join(pinned_drift), SKILLS_NPM_VERSION))
        rows.append(("warn", txt))
    d = read_diff_cache()
    if d and d.get("checked"):
        n = int(d.get("n") or 0)
        rows.append(("info" if not n else "warn", "%d updates waiting (upstream checked %s) → bin/skills-sync --diff" % (n, time.strftime("%Y-%m-%d", time.localtime(d["checked"])))))
    else:
        rows.append(("info", "skill updates not checked yet → bin/skills-sync --diff --online (weekly)"))
    try:
        uses = count_skill_uses(USES_DAYS, projects_dir, now=now)
    except Exception:
        uses = None
    if uses is None:
        rows.append(("info", "Skill-tool uses in %d days: UNKNOWN (transcripts not scanned yet; run shipm doctor --rows again)" % USES_DAYS))
    elif uses == 0:
        rows.append(("info", "0 Skill-tool uses in %d days (the roles have the Skill tool now; check again later)" % USES_DAYS))
    else:
        rows.append(("ok", "%d Skill-tool uses in %d days" % (uses, USES_DAYS)))
    for name, pdir in plist:
        sk = _read(Path(pdir) / "docs" / "SKILLS.md")
        if sk is not None:
            m = REVIEW_RE.search(sk)
            rv = m.group(1) if m else "not done"
            age = _days_since(rv, now) if rv != "not done" else None
            if age is not None and age > REVIEW_STALE_DAYS:
                rows.append(("warn", "%s: skills review is %d days old → shipm skills view %s" % (name, age, name)))
            sm = STACK_LINE_RE.search(sk)
            if sm and sm.group(1) not in ("", "unknown") and stack_of(pdir) not in (sm.group(1), "unknown"):
                rows.append(("warn", "%s: stack changed since the skills review (%s → %s) → repeat the review" % (name, sm.group(1), stack_of(pdir))))
        total = sum(description_bytes(Path(pdir) / ".agents" / "skills" / n) for n in project_skills(pdir) if (Path(pdir) / ".agents" / "skills" / n).is_dir())
        if total > DESC_WARN_BYTES:
            rows.append(("warn", "%s: project skill descriptions weigh %.1f KB in every prefix (limit 8 KB) → drop unused skills" % (name, total / 1024.0)))
    return rows


