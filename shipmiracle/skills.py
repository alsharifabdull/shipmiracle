def sync_main(argv: List[str], out=print, is_tty: Optional[bool] = None, ask=None) -> int:
    import argparse
    ap = argparse.ArgumentParser(prog="skills-sync", allow_abbrev=False, description="Install the approved skills at their pinned commit. Never updates anything by itself.")
    ap.add_argument("--dry", action="store_true", help="print what would happen; changes nothing, no network")
    ap.add_argument("--project", metavar="NAME_OR_DIR")
    ap.add_argument("--pack", metavar="PACK")
    ap.add_argument("--pin", action="store_true", help="resolve `unpinned` entries to a commit (needs --online)")
    ap.add_argument("--repin", metavar="NAME[,NAME]", help="with --pin --online: re-pin already pinned skills whose install hash fails (explicit names only; owner only)")
    ap.add_argument("--from-commit", metavar="NAME[,NAME]", help="with --pin --online: fill path + tree_sha256 of approved, commit-pinned, never-installed skills from the pinned commit (explicit names only; owner only)")
    ap.add_argument("--diff", action="store_true", help="the weekly diff against upstream")
    ap.add_argument("--online", action="store_true", help="allow network (git ls-remote / git clone) for --diff and --pin")
    ap.add_argument("--update", action="store_true", help="deprecated: never updates; behaves like --diff")
    try:
        a = ap.parse_args(argv)
    except SystemExit as e:
        return 2 if e.code else 0
    try:
        if a.update:
            out("note: --update no longer updates anything; skills change only when the owner pins a new commit. Showing the diff instead.")
            a.diff = True
        if a.repin is not None and not a.pin:
            out("refused: --repin goes with --pin --online.")
            return 2
        if a.from_commit is not None and (not a.pin or a.repin is not None):
            out("refused: --from-commit goes with --pin --online, and not with --repin.")
            return 2
        if a.pin:
            if not a.online:
                out("refused: --pin reads upstream repositories; add --online to allow the network.")
                return 2
            if a.from_commit is not None:
                rows_ = pin_from_commit(a.from_commit.split(","), out=out, is_tty=is_tty, ask=ask)
                for s, st, why in rows_:
                    out("  %-8s %s  %s" % (st, s, why))
                return 1 if any(st == "FAIL" for _s, st, _w in rows_) else 0
            names = [x for x in (a.repin or "").split(",") if x] if a.repin is not None else None
            rows_ = pin(only=names, repin=names is not None, out=out, is_tty=is_tty, ask=ask)
            for s, st, why in rows_:
                out("  %-8s %s  %s" % (st, s, why))
            return 1 if any(st == "FAIL" for _s, st, _w in rows_) else 0
        if a.diff:
            d = diff(online=a.online)
            if d.get("checked") is None:
                out("updates not checked (offline). %d skill(s) unpinned. Add --online to ask upstream." % len(d.get("unpinned", [])))
                return 0
            for u in d["updates"]:
                out("  update  %s (%s): pinned %s, upstream %s" % (u["skill"], u["pkg"], u["pinned"][:12], u["upstream"][:12]))
            if d["unpinned"]:
                out("  unpinned: %s" % ", ".join(d["unpinned"]))
            if d["unreachable"]:
                out("  unreachable: %s" % ", ".join(d["unreachable"]))
            out("%d updates waiting" % d["n"])
            return 0
        if a.project or a.pack:
            if not (a.project and a.pack):
                raise UsageError("--project and --pack go together")
            res = sync_project(a.project, a.pack, dry=a.dry, online=a.online)
        else:
            res = sync_global(dry=a.dry, online=a.online)
        bad = 0
        for s, st, why in res:
            out("  %-8s %s  %s" % (st, s, why))
            bad += st in ("FAIL", "offline")
        if any(st == "offline" for _s, st, _w in res):
            out("nothing installed: a pinned install clones the package; run again with --online.")
        if a.dry:
            out("DRY RUN: nothing was changed.")
        return 1 if bad else 0
    except ShipmiracleError as e:
        out("skills-sync: %s" % e)
        return e.exit_code
