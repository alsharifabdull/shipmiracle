def repo_url(pkg: str) -> str:
    base = os.environ.get("SHIPMIRACLE_SKILLS_REPO_BASE") if os.environ.get("SHIPMIRACLE_TEST") == "1" else None
    if not PKG_RE.fullmatch(pkg):
        raise UsageError("bad package name: %r" % pkg[:80])
    return os.path.join(base, pkg) if base else "https://github.com/%s.git" % pkg


def ls_remote_head(pkg: str) -> Optional[str]:
    """Upstream HEAD commit of a package (NETWORK). None on any failure."""
    try:
        p = _git(["ls-remote", repo_url(pkg), "HEAD"], timeout=30)
    except (OSError, subprocess.SubprocessError):
        return None
    sha = (p.stdout.split("\t")[0] if p.returncode == 0 and p.stdout else "").strip()
    return sha if SHA_RE.fullmatch(sha) else None


def diff(ws=None, online=False, now=None) -> dict:
    """Weekly diff. online=True asks each package's upstream HEAD with `git ls-remote` (the only network call) and caches the answer for the
    doctor row; online=False only reports from the cache. -> {"checked": ts|None, "updates": [...], "unpinned": [...], "unreachable": [...], "n": int}"""
    ws = _ws(ws)
    lock = load_lock(ws)
    pkgs = sorted({e["pkg"] for e in lock.values() if isinstance(e, dict) and "pkg" in e})
    if not online:
        c = read_diff_cache()
        if c:
            return c
        return {"checked": None, "updates": [], "unpinned": sorted(k for k, e in lock.items() if e.get("commit") == UNPINNED), "unreachable": [], "n": 0}
    heads = {p: ls_remote_head(p) for p in pkgs}
    updates, unpinned, unreachable = [], [], []
    for k in sorted(lock):
        e = lock[k]
        if heads.get(e.get("pkg")) is None:
            unreachable.append(k)
        elif e.get("commit") == UNPINNED:
            unpinned.append(k)
        elif heads[e["pkg"]] != e["commit"]:
            updates.append({"skill": k, "pkg": e["pkg"], "pinned": e["commit"], "upstream": heads[e["pkg"]]})
    res = {"checked": int(now if now is not None else time.time()), "updates": updates, "unpinned": unpinned, "unreachable": unreachable, "n": len(updates)}
    try:
        _atomic(_state_file("skills-diff.json"), json.dumps(res, indent=1) + "\n", 0o600)
    except OSError:
        pass
    return res


def count_skill_uses(days=USES_DAYS, projects_dir=None, budget_s=3.0, now=None) -> Optional[int]:
    """Number of Skill-tool calls in the Claude transcripts of the last `days` days, or None (unknown) when the folder is missing or the scan did not
    finish inside the time budget. Incremental: per-file counts are cached by (mtime, size) in the state folder, so each call finishes more files."""
    root = Path(projects_dir) if projects_dir else paths.home() / ".claude" / "projects"
    if not root.is_dir():
        return None
    now = now if now is not None else time.time()
    cache_path = _state_file("skills-uses.json")
    try:
        cache = json.loads(_read(cache_path) or "{}")
    except (ValueError, RecursionError):
        cache = {}
    cache = cache.get("files") if isinstance(cache, dict) and cache.get("v") == USES_CACHE_V and isinstance(cache.get("files"), dict) else {}
    t0 = time.time()
    total, done, dirty, seen = 0, True, False, {}
    for dp, _dn, fns in os.walk(str(root)):
        for fn in fns:
            if not fn.endswith(".jsonl"):
                continue
            full = os.path.join(dp, fn)
            try:
                st = os.stat(full)
            except OSError:
                continue
            if now - st.st_mtime > days * 86400:
                continue
            key = os.path.relpath(full, str(root))
            c = cache.get(key)
            if isinstance(c, list) and len(c) == 3 and c[0] == int(st.st_mtime) and c[1] == st.st_size:
                total += c[2]
                seen[key] = c
                continue
            if time.time() - t0 > budget_s:
                done = False
                continue
            n = 0
            try:
                with open(full, "rb") as f:
                    tail = b""
                    for chunk in iter(lambda: f.read(8 << 20), b""):
                        buf = tail + chunk
                        n += buf.count(b'"name":"Skill"')
                        tail = buf[-16:]
            except OSError:
                continue
            seen[key] = [int(st.st_mtime), st.st_size, n]
            total += n
            dirty = True
    if dirty or set(seen) != set(cache):
        try:
            _atomic(cache_path, json.dumps({"v": USES_CACHE_V, "files": seen}) + "\n", 0o600)
        except OSError:
            pass
    return total if done else None


